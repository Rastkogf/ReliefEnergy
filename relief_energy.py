from qgis.core import QgsProcessingAlgorithm, QgsApplication
from qgis.PyQt.QtCore import QCoreApplication, QLocale, QTranslator
from .relief_energy_provider import ReliefEnergyProvider

cmd_folder = os.path.split(inspect.getfile(inspect.currentframe()))[0]

if cmd_folder not in sys.path:
    sys.path.insert(0, cmd_folder)


class ReliefEnergyPlugin(object):

    def __init__(self):
        self.provider = None

        locale = QLocale(QgsApplication.locale())
        locale_path = os.path.join(
            os.path.dirname(__file__),
            "i18n",
            "relief_energy_{}.qm".format(locale.name()),
        )
        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

    def tr(self, message):
        return QCoreApplication.translate("ReliefEnergy", message)

    def initProcessing(self):
        """Init Processing provider for QGIS >= 3.8."""
        self.provider = ReliefEnergyProvider()
        QgsApplication.processingRegistry().addProvider(self.provider)

    def initGui(self):
        self.initProcessing()

    def unload(self):
        QgsApplication.processingRegistry().removeProvider(self.provider)
